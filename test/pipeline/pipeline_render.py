INTRO = """
# ---------------------------------------------------------------------------
# Omnia Single-Cluster Child Pipeline  (GENERATED by pipeline_render.py, do not edit)
# ---------------------------------------------------------------------------
# Triggered by the parent pipeline (.gitlab-ci.yml) with CLUSTER and PIPELINE_MODE.
#
#   PIPELINE_MODE=default  ->  cleanup, install, inputs, deploy and tests
#   PIPELINE_MODE=deploy   ->  inputs, deploy and tests (the Omnia venv must exist)
#   PIPELINE_MODE=cleanup  ->  cleanups only
#
# Flow of the default mode:
#   initialization (clone Omnia on the OIM, take the helpers from it) -> setup_environment
#   -> nfs_check -> cleanup_<domain> ...
#   -> cleanup_omnia (omnia.sh --cleanup --all, then the Slurm/K8s NFS shares)
#   -> setup_main (omnia.sh -s) -> test_main_installation -> inputs (all domains, one stage)
#   -> <domain> (exec mode) -> test_<domain> (verify) -> summary
#
# A failed cleanup does not stop the other cleanups; nothing is installed after it.
#
# Variables: DOMAINS (default, or a regex such as repo_manager|orchestrator), SKIP_STAGES,
# ENABLE_SETUP, ENABLE_DISCOVERY, TEST_MODE, DRY_RUN, VERBOSE, <DOMAIN>_TAGS (comma list of FVT
# tags run in exec mode), TEST_<DOMAIN>_CMD (verify command), BAO_* (OpenBao).
# Inputs: clusters/<name>/inputs/<domain>/ and clusters/<name>/inputs/omnia.env.
"""
VARIABLES = (("SSH_CONNECT_TIMEOUT", "30"), ("PIPELINE_VERSION", "4.0"), ("SKIP_STAGES", ""),
             ("TEST_MAIN_CMD", "./run_validation.sh fvt_main verify"),
             *((f"TEST_{d.upper()}_CMD", f"./run_validation.sh fvt_{d} verify")
               for d in ("repo_manager", "image_build_manager", "orchestrator", "discovery",
                         "telemetry")))
BOOTSTRAP = r"""
import os, re, shlex, subprocess, sys, time
def fail(message):
    print("ERROR: " + message, file=sys.stderr)
    sys.exit(1)
cluster = os.environ.get("CLUSTER", "")
if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,63}", cluster):
    fail("CLUSTER is empty or not a plain name")
prefix = cluster.upper().replace("-", "_")
ip, user, password = (os.environ.get(prefix + "_TARGET_" + n, "") for n in ("IP", "USER", "PASS"))
if not (ip and user and password):
    fail(prefix + "_TARGET_IP, _TARGET_USER and _TARGET_PASS must be set as CI/CD variables")
repo, branch = os.environ.get("OMNIA_REPO", ""), os.environ.get("OMNIA_BRANCH", "")
path = os.environ.get("OMNIA_INSTALL_PATH", "/root/omnia").rstrip("/")
if not re.fullmatch(r"(https?://|git@)[A-Za-z0-9._:/@~+-]+", repo):
    fail("OMNIA_REPO is empty or has unsafe characters")
if not re.fullmatch(r"[A-Za-z0-9._/-]{1,200}", branch):
    fail("OMNIA_BRANCH is empty or has unsafe characters")
protected = ("/", "/bin", "/boot", "/dev", "/etc", "/home", "/lib", "/lib64", "/media", "/mnt",
             "/opt", "/opt/omnia", "/proc", "/root", "/run", "/sbin", "/srv", "/sys", "/tmp",
             "/usr", "/var")
if not re.fullmatch(r"/[A-Za-z0-9._/-]+", path) or path in protected:
    fail("OMNIA_INSTALL_PATH '" + path + "' is not a safe folder of its own (e.g. /root/omnia)")
known = os.environ.get("PIPELINE_SSH_KNOWN_HOSTS") or os.environ.get(prefix + "_SSH_KNOWN_HOSTS")
if known:
    check = ["-o", "StrictHostKeyChecking=yes", "-o", "UserKnownHostsFile=" + known]
elif os.environ.get("PIPELINE_SSH_SKIP_HOST_KEY", "").lower() == "true":
    print("WARNING: the OIM host key is not checked (PIPELINE_SSH_SKIP_HOST_KEY=true)")
    check = ["-o", "StrictHostKeyChecking=no", "-o", "UserKnownHostsFile=/dev/null"]
else:
    fail("the OIM host key is required. HOW TO FIX: setup_gitlab_project.py --update "
         "--scan-host-keys stores " + prefix + "_SSH_KNOWN_HOSTS, or set "
         "PIPELINE_SSH_SKIP_HOST_KEY=true to accept the risk")
ssh = ["sshpass", "-e", "ssh"] + check + ["-o", "LogLevel=ERROR", "-o", "ServerAliveInterval=30",
       "-o", "ConnectTimeout=" + os.environ.get("SSH_CONNECT_TIMEOUT", "30"), user + "@" + ip]
env = dict(os.environ, SSHPASS=password)
q = shlex.quote
clone = ("set -e\n"
         "command -v git >/dev/null || dnf install -y git || yum install -y git || apt-get install -y git\n"
         "rm -rf " + q(path) + "\n"
         "mkdir -p " + q(os.path.dirname(path)) + "\n"
         "git clone -b " + q(branch) + " " + q(repo) + " " + q(path) + "\n")
for attempt in range(1, 6):
    rc = subprocess.run(ssh + ["bash", "-s"], input=clone.encode(), env=env).returncode
    if rc != 255:
        break
    print("SSH connection failed, retry " + str(attempt) + "/5 in 10s")
    time.sleep(10)
if rc:
    fail("cloning " + repo + " (" + branch + ") on the OIM failed (exit code " + str(rc) + ")")
os.makedirs("ci_tools", exist_ok=True)
pack = subprocess.Popen(ssh + ["tar -C " + q(path) + "/test/pipeline --exclude=__pycache__ -cf - "
                               "pipeline_ci.py library"], stdout=subprocess.PIPE, env=env)
subprocess.run(["tar", "-xf", "-", "-C", "ci_tools"], stdin=pack.stdout, check=False)
pack.stdout.close()
pack.wait()
if not os.path.isfile("ci_tools/pipeline_ci.py"):
    fail("the clone has no test/pipeline/pipeline_ci.py. HOW TO FIX: OMNIA_BRANCH of " + repo +
         " must be a branch that has the pipeline helpers")
print("Cloned " + repo + " (" + branch + ") to " + path + " and took the pipeline helpers from it")
"""
BEFORE_SCRIPT = ('git fetch origin "$CI_COMMIT_REF_NAME" 2>/dev/null && '
                 'git checkout "origin/$CI_COMMIT_REF_NAME" -- clusters/ 2>/dev/null || true')
AFTER_SCRIPT = ('mkdir -p "pipeline_job_status/$CI_PIPELINE_ID"',
                "printf '{\"name\":\"%s\",\"status\":\"%s\",\"url\":\"%s\"}\\n' \"$CI_JOB_NAME\" "
                "\"$CI_JOB_STATUS\" \"$CI_JOB_URL\" "
                "> \"pipeline_job_status/$CI_PIPELINE_ID/$CI_JOB_NAME.json\"")


def _q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


def _domain_condition(domain: str) -> str:
    return f'($DOMAINS == "default" || $DOMAINS =~ /{domain}/)'


def _job(name: str, stage: str, script: Sequence[str], conditions: Sequence[str],
         when: str = "on_success", needs: Optional[Sequence[str]] = None,
         optional: Sequence[str] = (), allow_failure: Optional[bool] = None,
         skip: Optional[str] = None, id_tokens: bool = False,
         artifacts: Sequence[str] = (), variables: Optional[dict] = None,
         python_blocks: Sequence[str] = ()) -> List[str]:
    """Return the YAML lines of one job. `skip` is the SKIP_STAGES word (default: the name)."""
    lines = [f"{name}:", f"  stage: {stage}", "  timeout: 3h"]
    if allow_failure is not None:
        lines.append(f"  allow_failure: {str(allow_failure).lower()}")
    if variables:
        lines += ["  variables:"] + [f"    {k}: {_q(v)}" for k, v in variables.items()]
    if id_tokens:
        lines += ["  id_tokens:", "    VAULT_ID_TOKEN:", "      aud: $BAO_SERVER_URL"]
    if needs or optional:
        lines.append("  needs:")
        lines += [f"    - job: {n}\n      artifacts: true" for n in (needs or ())]
        lines += [f"    - job: {n}\n      artifacts: true\n      optional: true" for n in optional]
    lines.append("  rules:")
    lines += [f"    - if: {_q(f'$SKIP_STAGES =~ /{skip or name}/')}", "      when: never"]
    lines += [f"    - if: {_q(c)}\n      when: {when}" for c in conditions]
    if artifacts:
        lines += ["  artifacts:", "    when: always", "    expire_in: 1 week", "    paths:"]
        lines += [f"      - {a}" for a in artifacts]
    lines.append("  script:")
    for block in python_blocks:
        lines += ["    - |", "      python3 - <<'PYEOF'"]
        lines += [f"      {row}" if row else "" for row in block.strip("\n").split("\n")]
        lines += ["      PYEOF"]
    lines += [f"    - python3 {HELPER} {s}" for s in script]
    return lines


def render() -> str:
    """Return the text of .gitlab-ci-cluster.yml."""
    stages = ["initialization", "setup_environment", "nfs_check",
              *(f"cleanup_{d}" for d in CLEANUP_ORDER), "cleanup_omnia", "setup_main",
              "test_main_installation", "inputs",
              *(s for d in DEPLOY_ORDER for s in (d, f"test_{d}")), "summary"]
    out = [LICENSE + INTRO, "workflow:", "  rules:",
           "    - if: '$CI_PIPELINE_SOURCE == \"parent_pipeline\"'", "      when: always", "",
           "variables:"]
    out += [f"  {k}: {_q(v)}" for k, v in VARIABLES]
    out += ["", "stages:"] + [f"  - {s}" for s in stages] + ["",
            "default:", "  retry:", "    max: 1", "    when:"]
    out += [f"      - {w}" for w in RETRY_WHEN]
    out += ["  before_script:", f"    - {_q(BEFORE_SCRIPT)}", "  after_script:"]
    out += [f"    - {_q(a)}" for a in AFTER_SCRIPT]
    out += ["  artifacts:", "    when: always", "    expire_in: 1 week", "    paths:",
            "      - pipeline_job_status/", ""]

    jobs: List[List[str]] = [
        _job("initialization", "initialization", ["init"], [ANY_MODE], allow_failure=False,
             artifacts=["pipeline_job_status/", "ci_tools/"], python_blocks=[BOOTSTRAP]),
        _job("setup_environment", "setup_environment", ["checkout"], [ANY_MODE],
             needs=["initialization"],
             artifacts=["pipeline_job_status/", "actual_commit_sha.txt"]),
        _job("nfs_check", "nfs_check", ["nfs-check"],
             [f'{CLEANUP_MODE} && $DOMAINS == "default"'], needs=["initialization",
             "setup_environment"], skip="nfs_check", artifacts=["pipeline_job_status/"]),
    ]
    previous: List[str] = []
    for domain in CLEANUP_ORDER:
        name = f"cleanup_{domain}"
        jobs.append(_job(name, name, [f"cleanup {domain}"],
                         [f"{CLEANUP_MODE} && {_domain_condition(domain)}"], when="always",
                         needs=["initialization", "setup_environment"], optional=list(previous),
                         allow_failure=domain in TOLERATED_CLEANUPS, skip=domain))
        previous.append(name)
    jobs.append(_job("cleanup_omnia", "cleanup_omnia", ["cleanup-omnia"],
                     [f'{CLEANUP_MODE} && $DOMAINS == "default"'], when="always",
                     needs=["initialization", "setup_environment"], optional=list(previous),
                     allow_failure=False))
    jobs.append(_job("setup_main", "setup_main", ["install"],
                     ['$PIPELINE_MODE == "default"', '$ENABLE_SETUP == "true"']))
    jobs.append(_job("test_main_installation", "test_main_installation", ["verify main"],
                     [f'{DEPLOY_MODE} && $TEST_MODE == "true"']))
    jobs.append(_job("inputs", "inputs", ["inputs"], [DEPLOY_MODE]))
    for domain in DEPLOY_ORDER:
        extra = '$ENABLE_DISCOVERY == "true" && ' if domain == "discovery" else ""
        jobs.append(_job(domain, domain, [f"deploy {domain}"],
                         [f"{extra}{DEPLOY_MODE} && {_domain_condition(domain)}"],
                         id_tokens=True))
        jobs.append(_job(f"test_{domain}", f"test_{domain}", [f"verify {domain}"],
                         [f'{extra}{DEPLOY_MODE} && $TEST_MODE == "true" && '
                          f"{_domain_condition(domain)}"], allow_failure=True,
                         skip=domain, id_tokens=True))
    summary = _job("summary", "summary", ["summary"], [ANY_MODE], when="always",
                   allow_failure=True, artifacts=["pipeline_reports/", "pipeline_job_status/"],
                   variables={"PIPELINE_JOB_ORDER": ",".join(s for s in stages if s != "summary")})
    jobs.append(summary)
    for lines in jobs:
        out += lines + [""]
    return "\n".join(out)


def main(argv: List[str]) -> int:
    if argv == ["--write"]:
        with open(OUTPUT, "w", encoding="utf-8") as handle:
            handle.write(render())
        print(f"wrote {OUTPUT}")
        return 0
    if argv == ["--check"]:
        with open(OUTPUT, encoding="utf-8") as handle:
            same = handle.read() == render()
        print("up to date" if same else f"{OUTPUT} differs: run pipeline_render.py --write")
        return 0 if same else 1
    print(__doc__)
    return 2


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
